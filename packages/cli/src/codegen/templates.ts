import { ComponentSpec } from '@josephbrendan/schema';
import { buildCvaDefinition } from './cva.js';

export interface TemplateContext {
  spec: ComponentSpec;
  kitName: string;
  exportedAt: string;
  reactVersion: number;
  cnImportPath: string;
}

function makeHeader(ctx: TemplateContext, hasRaw: boolean, isGeneric = false): string {
  const lines = [
    `// Generated by Frame-Relay from ${ctx.kitName}, exported ${ctx.exportedAt}. Safe to edit. Sync keeps your changes.`,
  ];
  if (isGeneric) {
    lines.push(
      '// frame-relay: generated shell. Agent: refine using .frame-relay/components.md and the screenshots.',
    );
  }
  if (hasRaw) {
    lines.push(
      '// frame-relay: raw value from Figma. Bind it to a variable in Figma to use a token.',
    );
  }
  return lines.join('\n');
}

function getVariantHelpers(variantKeys: string[]) {
  const destructure = variantKeys.length > 0 ? variantKeys.join(', ') + ', ' : '';
  const args = variantKeys.length > 0 ? `{ ${variantKeys.join(', ')} }` : '{}';
  return { destructure, args };
}

export function renderButtonTemplate(ctx: TemplateContext): string {
  const { spec, reactVersion, cnImportPath } = ctx;
  const cva = buildCvaDefinition(spec, 'buttonVariants', [
    'inline-flex',
    'items-center',
    'justify-center',
    'cursor-pointer',
    'transition-colors',
    'focus-visible:outline-none',
    'disabled:pointer-events-none',
  ]);

  const header = makeHeader(ctx, cva.hasRaw);
  const isReact19 = reactVersion >= 19;
  const vKeys = cva.variantTypeProps.length > 0 ? cva.variantTypeProps : ['variant', 'size'];
  const { destructure: vDestructure, args: vArgs } = getVariantHelpers(vKeys);

  return `${header}
import * as React from 'react';
import { cva, type VariantProps } from 'class-variance-authority';
import { cn } from '${cnImportPath}';

${cva.cvaCode}

export interface ButtonProps
  extends React.ButtonHTMLAttributes<HTMLButtonElement>,
    VariantProps<typeof buttonVariants> {
  leftIcon?: React.ReactNode;
  rightIcon?: React.ReactNode;
  loading?: boolean;
}

${
  isReact19
    ? `export function Button({
  className,
  ${vDestructure}leftIcon,
  rightIcon,
  loading = false,
  disabled,
  children,
  type = 'button',
  ref,
  ...props
}: ButtonProps & { ref?: React.Ref<HTMLButtonElement> }) {
  return (
    <button
      ref={ref}
      type={type}
      disabled={disabled || loading}
      data-loading={loading ? 'true' : undefined}
      className={cn(buttonVariants(${vArgs}), className)}
      {...props}
    >
      {leftIcon && <span className="mr-2 inline-flex items-center shrink-0">{leftIcon}</span>}
      {children}
      {rightIcon && <span className="ml-2 inline-flex items-center shrink-0">{rightIcon}</span>}
    </button>
  );
}`
    : `export const Button = React.forwardRef<HTMLButtonElement, ButtonProps>(
  ({ className, ${vDestructure}leftIcon, rightIcon, loading = false, disabled, children, type = 'button', ...props }, ref) => {
    return (
      <button
        ref={ref}
        type={type}
        disabled={disabled || loading}
        data-loading={loading ? 'true' : undefined}
        className={cn(buttonVariants(${vArgs}), className)}
        {...props}
      >
        {leftIcon && <span className="mr-2 inline-flex items-center shrink-0">{leftIcon}</span>}
        {children}
        {rightIcon && <span className="ml-2 inline-flex items-center shrink-0">{rightIcon}</span>}
      </button>
    );
  }
);
Button.displayName = 'Button';`
}
`;
}

