export function renderGenericTemplate(ctx: TemplateContext): string {
  const { spec, reactVersion, cnImportPath } = ctx;
  const compName = spec.name;
  const cvaName = `${compName.charAt(0).toLowerCase() + compName.slice(1)}Variants`;
  const cva = buildCvaDefinition(spec, cvaName);

  const header = makeHeader(ctx, cva.hasRaw, true);
  const isReact19 = reactVersion >= 19;
  const role = spec.accessibility?.role ? `role="${spec.accessibility.role}"` : '';
  const { destructure: vDestructure, args: vArgs } = getVariantHelpers(cva.variantTypeProps);

  return `${header}
import * as React from 'react';
import { cva, type VariantProps } from 'class-variance-authority';
import { cn } from '${cnImportPath}';

${cva.cvaCode}

export interface ${compName}Props
  extends React.HTMLAttributes<HTMLDivElement>,
    VariantProps<typeof ${cvaName}> {}

${
  isReact19
    ? `export function ${compName}({ className, ${vDestructure}children, ref, ...props }: ${compName}Props & { ref?: React.Ref<HTMLDivElement> }) {
  return (
    <div ref={ref} ${role} className={cn(${cvaName}(${vArgs}), className)} {...props}>
      {children}
    </div>
  );
}`
    : `export const ${compName} = React.forwardRef<HTMLDivElement, ${compName}Props>(
  ({ className, ${vDestructure}children, ...props }, ref) => {
    return (
      <div ref={ref} ${role} className={cn(${cvaName}(${vArgs}), className)} {...props}>
        {children}
      </div>
    );
  }
);
${compName}.displayName = '${compName}';`
}
`;
}

export function selectTemplate(ctx: TemplateContext): string {
  const name = ctx.spec.name.toLowerCase();
  const category = (ctx.spec.category || '').toLowerCase();

  if (name === 'button' || category === 'button') return renderButtonTemplate(ctx);
  if (name === 'input' || category === 'input') return renderInputTemplate(ctx);
  if (name === 'textarea' || category === 'textarea') return renderTextareaTemplate(ctx);
  if (name === 'select' || category === 'select') return renderSelectTemplate(ctx);
  if (name === 'checkbox' || category === 'checkbox') return renderCheckboxTemplate(ctx);
  if (name === 'radio' || category === 'radio') return renderRadioTemplate(ctx);
  if (name === 'switch' || category === 'switch') return renderSwitchTemplate(ctx);
  if (name === 'card' || category === 'card') return renderCardTemplate(ctx);
  if (name === 'badge' || category === 'badge') return renderBadgeTemplate(ctx);
  if (name === 'modal' || name === 'dialog' || category === 'modal' || category === 'dialog')
    return renderModalTemplate(ctx);
  if (name === 'tabs' || category === 'tabs') return renderTabsTemplate(ctx);

  return renderGenericTemplate(ctx);
}
